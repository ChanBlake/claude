def emit(path):
    out = ["/* DRIFT — sector data.  GENERATED by tools/compose.py — edit chambers there.\n"
           "   Verified by tools/verify.mjs; never hand-edit geometry without re-running it.\n*/\n\n",
           ZONES_SRC, "\nexport const LEVELS=[\n"]
    for L in LEVELS:
        rows = ",\n".join('"%s"' % r for r in L["rows"])
        extra = ""
        if L["mp"]:
            mp = ",\n    ".join(
                '{c:%d,r:%d,w:%d,axis:%s,dist:%d,speed:%s,phase:%s}'
                % (m["c"], m["r"], m["w"], json.dumps(m["axis"]), m["dist"], m["speed"], m["phase"])
                for m in L["mp"])
            extra = ",\n mp:[\n    %s]" % mp
        out.append('{name:%s,kit:%s,par:%d,teach:%s,hint:%s,rows:[\n%s]%s},\n\n'
                   % (json.dumps(L["name"]), json.dumps(L["kit"]), L["par"],
                      "true" if L["teach"] else "false",
                      json.dumps(L["hint"]), rows, extra))
    out.append("];\n")
    open(path, "w").write("".join(out))

