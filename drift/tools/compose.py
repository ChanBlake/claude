#!/usr/bin/env python3
"""DRIFT — sector composer.

Sectors are built from 25x15 CHAMBERS joined edge to edge. The join drops the
shared border column and replaces it with a doorway on the rows you name, so a
3-stage sector is 73 tiles wide and a 4-stage one is 97, and the camera scrolls.

Composing rather than hand-typing 73-character rows is the point: the single most
common way to break a level is a row one character short, and that class of
mistake cannot happen here — every chamber is validated at 25x15 and the join
arithmetic is fixed.

    python3 tools/compose.py        regenerate src/levels.js
    node tools/verify.mjs           prove every sector is still solvable

TILES
    #  hull                    ~  brittle plating (one use, never restored)
    -  drop-through plating    :  false wall — looks like hull, walk through it
    ^  hazard                  =  lattice ALPHA (solid at phase 0)
    Z  null field              %  lattice BETA  (solid at phase 1)
    D  door                    T  phase coupler (persists through rewind)
    S  latch switch            B  pressure plate
    C  loose cargo (rewinds)   A  anchored cargo (does not)
    o  data core               P  spawn        E  airlock

Cores are optional but all of a sector's cores are needed for its 100% mark.
Hiding one behind a false wall is fair because the verifier proves every core
reachable — a secret can be well hidden without ever being unfair.
"""
import json, os

CW, CH = 25, 15

def C(block):
    rows = [r for r in block.strip("\n").split("\n")]
    assert len(rows) == CH, f"chamber has {len(rows)} rows, need {CH}"
    for i, r in enumerate(rows):
        assert len(r) == CW, f"row {i} is {len(r)} wide, need {CW}: {r!r}"
    return rows

def M(rows):
    """Mirror a chamber. Geometry that worked one way works reversed, which makes
       this a safe way to extend a sector without risking a dead end."""
    return [r[::-1] for r in rows]

def secret(rows, r, c, dirn="left", n=2):
    """Carve an n-tile pocket at (r,c) behind a false wall, with a core at the end."""
    g = [list(x) for x in rows]
    step = -1 if dirn == "left" else 1
    g[r][c] = ":"
    for i in range(1, n + 1):
        g[r][c + step * i] = "."
    g[r][c + step * n] = "o"
    return ["".join(x) for x in g]

def keep_one(rows, ch, last):
    """A stage that used to end a sector still carries its airlock. The exit
       belongs to whichever stage is last, the spawn to whichever is first."""
    hits = [(r, c) for r, row in enumerate(rows) for c, x in enumerate(row) if x == ch]
    if len(hits) <= 1:
        return rows
    keep = hits[-1] if last else hits[0]
    g = [list(r) for r in rows]
    for r, c in hits:
        if (r, c) != keep:
            g[r][c] = "."
    return ["".join(r) for r in g]

def join(chambers, doors):
    assert len(doors) == len(chambers) - 1, "one seam per pair of chambers"
    out = list(chambers[0])
    for k, nxt in enumerate(chambers[1:]):
        seam = set(doors[k])
        out = [out[r][:-1] + ("." if r in seam else "#") + nxt[r][1:] for r in range(CH)]
    return out

