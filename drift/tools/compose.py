PLACE_SECRETS = True

def place_secret(name, rows):
    g = [list(r) for r in rows]
    if name in SECRET_WALL:
        r, c, dirn, n = SECRET_WALL[name]
        step = -1 if dirn == "left" else 1
        g[r][c] = ":"
        for i in range(1, n + 1):
            g[r][c + step * i] = "."
        g[r][c + step * n] = "o"
    elif name in SECRET_SPOT:
        r, c = SECRET_SPOT[name]
        g[r][c] = "o"
    return ["".join(r) for r in g]

LEVELS = []
def S(name, kit, par, hint, chambers, doors, mp=None, teach=False):
    rows = join(chambers, doors)
    rows = place_secret(name, rows) if PLACE_SECRETS else rows
    rows = keep_one(rows, "E", last=True)
    rows = keep_one(rows, "P", last=False)
    LEVELS.append(dict(name=name, kit=kit, par=par, hint=hint, rows=rows, mp=mp, teach=teach))

